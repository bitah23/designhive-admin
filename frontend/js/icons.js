const SVG_ATTRS = {
  xmlns: 'http://www.w3.org/2000/svg',
  viewBox: '0 0 24 24',
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '2',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
  'aria-hidden': 'true',
};

/**
 * Replace every `[data-lucide]` placeholder inside `root` with its SVG.
 *
 * Rendered icons are marked, so the repeat calls pages make after each
 * re-render only touch placeholders added since the previous pass.
 */
function createIcons(options = {}) {
  const root = options.root || document;

  root.querySelectorAll('[data-lucide]:not([data-icon])').forEach(node => {
    const name = node.getAttribute('data-lucide');
    const paths = ICON_PATHS[name];

    if (!paths) {
      console.warn(`[icons] unknown icon "${name}"`);
      node.setAttribute('data-icon', '');
      return;
    }

    const svg = document.createElementNS(SVG_ATTRS.xmlns, 'svg');
    Object.entries(SVG_ATTRS).forEach(([key, value]) => svg.setAttribute(key, value));
    svg.innerHTML = paths;

    // Carry the placeholder's own attributes across — call sites reach for
    // these icons by `id` (logs.html spins #refresh-icon) and hang `title`
    // and `data-*` off them, so dropping them breaks those pages.
    Array.from(node.attributes).forEach(attr => {
      if (attr.name !== 'data-lucide') svg.setAttribute(attr.name, attr.value);
    });

    svg.setAttribute('data-icon', name);
    svg.setAttribute('class', `icon${node.className ? ' ' + node.className : ''}`);

    // Call sites size and colour icons with an inline style; default to 16px.
    if (!node.hasAttribute('style')) {
      svg.setAttribute('width', '16');
      svg.setAttribute('height', '16');
    }

    node.replaceWith(svg);
  });
}

/** Return an `<svg>` string for `name` — for composing markup in a template. */
function iconMarkup(name, size = 16, extraStyle = '') {
  const attrs = Object.entries({ ...SVG_ATTRS, width: size, height: size })
    .map(([key, value]) => `${key}="${value}"`)
    .join(' ');
  const style = extraStyle ? ` style="${extraStyle}"` : '';
  return `<svg ${attrs} data-icon="${name}" class="icon"${style}>${ICON_PATHS[name] || ''}</svg>`;
}

window.lucide = { createIcons, iconMarkup, icons: ICON_PATHS };
